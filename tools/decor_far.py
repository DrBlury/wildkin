def brazier_frames():
    """An iron fire bowl on a tripod; its flames dance (3 frames)."""
    frames = []
    for f in range(3):
        img = BRAZIER_BOWL.copy()
        for y in range(0, 9):
            for x in range(2, 14):
                if img.p[y][x] is not None:
                    continue
                h = 8 - y
                w = 5.2 - h * 0.6 + math.sin(y * 1.1 + f * 2.0) * 0.8
                cx = 7.5 + math.sin(y * 0.7 + f * 1.7) * 0.9
                d = abs(x + 0.5 - cx)
                if d < w * 0.35 and h < 6:
                    img.p[y][x] = 'lv_y'
                elif d < w * 0.7:
                    img.p[y][x] = 'lv_o'
                elif d < w:
                    img.p[y][x] = 'lv_r'
        frames.append(img)
    return frames


