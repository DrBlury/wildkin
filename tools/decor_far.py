def steam_vent_frames():
    """A fumarole: a sulfur-crusted stone ring with steam puffing up through
    the cell above (4 frames). 1x2, the top cell over people."""
    frames = []
    for f in range(4):
        img = Img(16, 32)
        img.paste(VENT, 0, 16)
        # puffs rising: each puff is a soft blob moving up 6px per frame
        for (k, x0) in enumerate((6.5, 9.0, 7.5)):
            yc = 26 - ((f * 6 + k * 8) % 24)
            r = 1.6 + (26 - yc) * 0.12
            xc = x0 + math.sin((yc + k) * 0.35) * 1.5
            for y in range(32):
                for x in range(16):
                    d = math.hypot(x + 0.5 - xc, (y + 0.5 - yc) * 1.2)
                    if d <= r and img.p[y][x] is None:
                        img.p[y][x] = 'white' if d < r * 0.55 else 'st_lt'
                    elif d <= r + 0.8 and img.p[y][x] is None and y < 26:
                        img.p[y][x] = 'st_mid' if (x + y + f) % 2 else None
        frames.append(img)
    return frames


